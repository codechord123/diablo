const SEEN_KEY = (nick, id) => `fd:story:${nick}:${id}`;
export function hasSeenStory(nickname, id) {
  return localStorage.getItem(SEEN_KEY(nickname, id)) === '1';
}
export function markSeenStory(nickname, id) {
  localStorage.setItem(SEEN_KEY(nickname, id), '1');
}

